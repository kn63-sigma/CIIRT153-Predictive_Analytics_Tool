def validate_inputs_gate(cost_m_2026, craft_shares):
    """Data Validation Gate: Verifies non-zero positive bounds and normalization integrity."""
    sanitized_cost = float(np.clip(cost_m_2026, 0.1, 5000.0))
    raw_sum = sum(craft_shares.values())

    if raw_sum <= 0:
        sanitized_shares = {
            "Piping": 35.0, "Electrical & Instrumentation": 20.0, "Civil": 15.0,
            "Structural": 10.0, "Equipment Installation": 10.0, "Other Crafts": 10.0
        }
    else:
        sanitized_shares = {k: (v / raw_sum) * 100.0 for k, v in craft_shares.items()}

    return sanitized_cost, sanitized_shares

def run_knn_staffing_model(
    cost_m_2026,
    facility_type,
    eng_comp,
    craft_shares,
    delivery_method="EPC (Engineer-Procure-Construct)",
    contract_type="Cost-Reimbursable / Cost Plus",
    k_neighbors=3
):
    # Pass inputs through Data Validation Gate
    cost_m_2026, craft_shares = validate_inputs_gate(cost_m_2026, craft_shares)

    # 1. Vector Feature Encoding
    user_sector_risk = SECTOR_RISK_MAP.get(facility_type, 1.00)
    user_log_cost = np.log(cost_m_2026)
    user_engr_val = ENGINEERING_TIERS.get(eng_comp, 0.50)

    df = df_database.copy()

    # Normalization spans so all three features map onto a common [0, 1] scale
    min_log_cost = np.log(df['cost_2026'].min())
    max_log_cost = np.log(df['cost_2026'].max())
    log_cost_span = max(0.01, max_log_cost - min_log_cost)

    min_sec = min(SECTOR_RISK_MAP.values())
    max_sec = max(SECTOR_RISK_MAP.values())
    sec_span = max(0.01, max_sec - min_sec)

    # Feature Importance Hierarchy (on normalized [0, 1] differences):
    # #1 Design Readiness (2.5) > #2 Facility Sector & Code Rigor (2.0) > #3 Project Scale (1.5)
    W_ENGR = 2.5
    W_SECTOR = 2.0
    W_COST = 1.5

    # 2. Normalized Weighted Euclidean Distance Metric
    distances = []
    for _, row in df.iterrows():
        p_sector_risk = SECTOR_RISK_MAP.get(row['sector'], 1.00)
        p_log_cost = np.log(row['cost_2026'])
        p_engr_val = row['engr_val']

        d_engr = abs(user_engr_val - p_engr_val)
        d_sector_risk = abs(user_sector_risk - p_sector_risk) / sec_span
        d_sector_cat = 0.0 if row['sector'] == facility_type else 0.15  # Exact-sector tie-breaker
        d_sector = min(1.0, d_sector_risk + d_sector_cat)
        d_cost = min(1.0, abs(user_log_cost - p_log_cost) / log_cost_span)

        d = np.sqrt(
            W_ENGR * (d_engr ** 2) +
            W_SECTOR * (d_sector ** 2) +
            W_COST * (d_cost ** 2)
        )
        distances.append(round(d, 4))

    df['distance'] = distances

    # 3. K-Nearest Neighbor Selection with Epsilon Gate
    EPSILON = 1e-4
    nearest_neighbors = df.sort_values(by='distance').head(k_neighbors).copy()
    inv_weights = [1.0 / max(EPSILON, d) for d in nearest_neighbors['distance']]
    sum_inv_w = sum(inv_weights)
    norm_weights = [w / sum_inv_w for w in inv_weights]

    knn_predicted_rework = sum(r * w for r, w in zip(nearest_neighbors['rework_pct'], norm_weights))
    knn_predicted_rework = float(np.clip(knn_predicted_rework, 0.5, 18.0))

    # 4. Project Exposure Index (PEI) via Sub-Linear Power Scaling & Execution Multipliers
    effective_cost_2026 = COST_ANCHOR_2026 * np.power(cost_m_2026 / COST_ANCHOR_2026, 0.72)
    m_engr_mult = 1.50 if user_engr_val < 0.2 else (1.00 if user_engr_val < 0.8 else 0.80)
    m_delivery = DELIVERY_RISK_MAP.get(delivery_method, 1.00)
    m_contract = CONTRACT_RISK_MAP.get(contract_type, 1.00)

    pei = (effective_cost_2026 / COST_ANCHOR_2026) * 10.0 * user_sector_risk * m_engr_mult * m_delivery * m_contract
    raw_qc = pei / 10.0

    # 5. Discrete Discipline Rounding Engine
    weighted_shares = {}
    total_w_share = 0.0
    for craft, pct in craft_shares.items():
        w = REGULARIZED_CRAFT_WEIGHTS.get(craft, 1.00)
        val = (pct / 100.0) * w
        weighted_shares[craft] = val
        total_w_share += val

    qc_breakdown = {}
    raw_quotas = {}

    for craft, val in weighted_shares.items():
        if craft_shares[craft] <= 0:
            qc_breakdown[craft] = 0
            raw_quotas[craft] = 0.0
        else:
            q_d = raw_qc * (val / max(0.01, total_w_share))
            raw_quotas[craft] = round(q_d, 2)

            # Mandatory Minimum Hold-Point Rule (0 < q_d < 1.0 -> 1 inspector)
            if q_d < 1.0:
                qc_breakdown[craft] = 1
            else:
                # GC Prudence Rule (q_d >= 1.0 -> standard 0.5 threshold)
                qc_breakdown[craft] = int(math.floor(q_d + 0.5))

    total_whole_qc = sum(qc_breakdown.values())
    risk_level = "Low Risk" if pei < 25 else ("Moderate Risk" if pei <= 60 else "High Risk")

    return {
        "pei": round(pei, 2),
        "effective_cost": round(effective_cost_2026, 2),
        "raw_qc": round(raw_qc, 2),
        "raw_quotas": raw_quotas,
        "total_whole_qc": total_whole_qc,
        "predicted_rework": round(knn_predicted_rework, 2),
        "risk_level": risk_level,
        "qc_breakdown": qc_breakdown,
        "nearest_neighbors": nearest_neighbors
    }

