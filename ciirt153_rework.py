CRAFT_KEYS = ["piping", "elec", "civil", "struct", "eqpt", "other"]

def adjust_crafts(changed_key):
    """Proportionally rebalances other sliders so the total across all crafts strictly equals 100%."""
    new_val = st.session_state[changed_key]
    other_keys = [k for k in CRAFT_KEYS if k != changed_key]
    current_other_sum = sum(st.session_state[k] for k in other_keys)
    target_other_sum = 100 - new_val

    if target_other_sum <= 0:
        st.session_state[changed_key] = 100
        for k in other_keys:
            st.session_state[k] = 0
    elif current_other_sum > 0:
        scale = target_other_sum / current_other_sum
        adjusted_vals = {k: int(round(st.session_state[k] * scale)) for k in other_keys}
        diff = target_other_sum - sum(adjusted_vals.values())
        if diff != 0:
            largest_other = max(other_keys, key=lambda k: st.session_state[k])
            adjusted_vals[largest_other] += diff
        for k, v in adjusted_vals.items():
            st.session_state[k] = max(0, v)
    else:
        bm_defaults = {"piping": 35, "elec": 20, "civil": 15, "struct": 10, "eqpt": 10, "other": 10}
        bm_other_sum = sum(bm_defaults[k] for k in other_keys)
        adjusted_vals = {k: int(round(target_other_sum * (bm_defaults[k] / bm_other_sum))) for k in other_keys}
        diff = target_other_sum - sum(adjusted_vals.values())
        if diff != 0:
            adjusted_vals[other_keys[0]] += diff
        for k, v in adjusted_vals.items():
            st.session_state[k] = max(0, v)

